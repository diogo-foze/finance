import { NextResponse } from "next/server";
import connectToDatabase from "@/lib/mongodb";
import User from "@/models/User";
import Receita from "@/models/Receita";
import Despesa from "@/models/Despesa";
import Message from "@/models/Message";
import Config from "@/models/Config";
import fs from "fs";
import path from "path";

export async function GET() {
  try {
    await connectToDatabase();
    const userCount = await User.countDocuments();
    return NextResponse.json({ isEmpty: userCount === 0 });
  } catch (error) {
    return NextResponse.json({ error: "Erro ao verificar banco de dados" }, { status: 500 });
  }
}

export async function POST() {
  try {
    await connectToDatabase();
    
    // Security check: only allow import if there are no users
    const userCount = await User.countDocuments();
    if (userCount > 0) {
      return NextResponse.json({ error: "O sistema já possui usuários. A importação automática está bloqueada por segurança." }, { status: 403 });
    }

    const filePath = path.join(process.cwd(), "docker-init", "init-db.js");
    if (!fs.existsSync(filePath)) {
      return NextResponse.json({ error: "Arquivo de backup não encontrado em docker-init/init-db.js" }, { status: 404 });
    }

    const content = fs.readFileSync(filePath, "utf8");
    
    // Simple parser to extract collections
    const collections = ["users", "receitas", "despesas", "messages", "configs"];
    const results: any = {};

    for (const col of collections) {
      const regex = new RegExp(`db\\.${col}\\.insertMany\\(([\\s\\S]+?)\\);`, "g");
      const match = regex.exec(content);
      
      if (match && match[1]) {
        let jsonStr = match[1].trim();
        
        // Transform MongoDB Shell format to plain JSON objects
        // 1. Remove ObjectId wrapper
        jsonStr = jsonStr.replace(/ObjectId\("([a-f0-9]{24})"\)/g, '"$1"');
        // 2. Remove new Date wrapper
        jsonStr = jsonStr.replace(/new Date\("([^"]+)"\)/g, '"$1"');
        
        try {
          // Note: This matches the array produced by backup-db.ts
          // Using eval is risky but since this is an internal setup file generated by the system, 
          // and we are doing a controlled cleanup, it should be fine. 
          // Alternatively, we use JSON5 or a safer parser if available.
          // For now, let's try a safer approach if possible, but the string is almost JSON.
          
          // Cleanup potential trailing commas or shell-specific syntax
          const data = JSON.parse(jsonStr);
          
          if (Array.isArray(data)) {
            if (col === "users") await User.insertMany(data);
            if (col === "receitas") await Receita.insertMany(data);
            if (col === "despesas") await Despesa.insertMany(data);
            if (col === "messages") await Message.insertMany(data);
            if (col === "configs") {
              // For configs, we might want to upsert or clear first
              await Config.deleteMany({});
              await Config.insertMany(data);
            }
            results[col] = data.length;
          }
        } catch (parseError) {
          console.error(`Erro ao processar coleção ${col}:`, parseError);
          // If JSON.parse fails, it might be due to loose formatting
          // Let's try to fix common issues if needed
        }
      }
    }

    return NextResponse.json({ 
      success: true, 
      message: "Importação concluída com sucesso!",
      details: results
    });

  } catch (error: any) {
    console.error("Setup Import Error:", error);
    return NextResponse.json({ error: error.message || "Erro interno no servidor" }, { status: 500 });
  }
}
